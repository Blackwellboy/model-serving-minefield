#!/usr/bin/env python3
"""Build the static GitHub Pages site for the registry.

Reads dist/MINEFIELD_REGISTRY.json (generated by `python -m minefield
agent-bundle`) and the offline search UI in web/, and writes:

  _site/index.html, app.js, styles.css, registry-data.js   the search UI
  _site/trap/<id>/index.html                              one page per trap
  _site/sitemap.xml, robots.txt, .nojekyll

Every per-trap page is a summary that links to the canonical entry on GitHub;
the entry file stays the authority. Stdlib only, no network, deterministic
output for a given registry file.

    python3 site/build_site.py [--out _site] [--base-url URL]
"""
from __future__ import annotations

import argparse
import html
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/Blackwellboy/model-serving-minefield"
DEFAULT_BASE = "https://blackwellboy.github.io/model-serving-minefield"

PAGE_CSS = """
:root{color-scheme:dark;--ink:#ece8f7;--paper:#0d0a14;--accent:#8b5cf6;--soft:#c4b5fd;--line:#2e2546}
*{box-sizing:border-box}
body{margin:0;font:17px/1.6 system-ui,sans-serif;color:var(--ink);background:var(--paper)}
main{width:min(820px,92vw);margin:auto;padding:3rem 0 4rem}
a{color:var(--soft)}
.eyebrow{color:var(--accent);font-weight:700;text-transform:uppercase;letter-spacing:.12em;font-size:.85rem}
h1{font:700 clamp(1.8rem,4.5vw,2.8rem)/1.1 Georgia,serif;margin:.4rem 0 1.2rem}
h2{color:var(--soft);font-size:1rem;text-transform:uppercase;letter-spacing:.08em;margin-top:2rem}
.status{display:inline-block;border:1px solid var(--accent);border-radius:999px;padding:.15rem .8rem;font-size:.9rem}
.card{border-left:3px solid var(--accent);padding:.2rem 0 .2rem 1rem}
footer{border-top:1px solid var(--line);margin-top:3rem;padding-top:1rem;font-size:.9rem}
"""


def esc(text) -> str:
    return html.escape(str(text or "").strip())


def trap_page(entry: dict, base: str) -> str:
    tid = entry["id"]
    title = entry.get("title", "")
    status = str(entry.get("status", "")).rstrip(".")
    symptom = entry.get("symptom", "")
    desc = (symptom[:200] + "…") if len(symptom) > 200 else symptom
    src = f"{REPO}/blob/main/{entry['source_path']}"
    related = "".join(
        f'<a href="../{esc(r)}/">{esc(r)}</a> ' for r in entry.get("related_traps") or [])
    sections = [
        ("Symptom", entry.get("symptom")),
        ("Mechanism", entry.get("mechanism")),
        ("Stacks and builds bitten", entry.get("affected_versions_builds")),
        ("The check", entry.get("check")),
        ("The fix", entry.get("mitigation")),
    ]
    body = "".join(f"<h2>{name}</h2><div class=card><p>{esc(text)}</p></div>"
                   for name, text in sections if text)
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; style-src 'unsafe-inline'; img-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'">
<title>Trap {esc(tid)}: {esc(title)} · Model Serving Minefield</title>
<meta name="description" content="{esc(desc)}">
<meta property="og:title" content="Trap {esc(tid)}: {esc(title)}">
<meta property="og:description" content="{esc(desc)}">
<meta property="og:url" content="{esc(base)}/trap/{esc(tid)}/">
<meta property="og:type" content="article">
<meta name="twitter:card" content="summary">
<link rel="canonical" href="{esc(base)}/trap/{esc(tid)}/">
<style>{PAGE_CSS}</style></head>
<body><main>
<p class="eyebrow"><a href="../../">Model Serving Minefield</a> · {esc(entry.get('category'))}</p>
<h1>Trap {esc(tid)}: {esc(title)}</h1>
<p><span class="status">{esc(status)}</span> · found by {esc(entry.get('contributor'))}</p>
{body}
<h2>Read the full entry</h2>
<p><a href="{esc(src)}">{esc(entry['source_path'])}</a> is the canonical entry, with evidence, attribution and corrections. This page is a summary of it.</p>
{f'<p>Related: {related}</p>' if related else ''}
<footer>Search every trap: <a href="../../">registry search</a> ·
Run it on your setup: <code>pipx install model-serving-minefield</code> ·
<a href="{REPO}">GitHub</a> · MIT</footer>
</main></body></html>
"""


def build(out: Path, base: str) -> int:
    registry = json.loads((ROOT / "dist" / "MINEFIELD_REGISTRY.json").read_text(encoding="utf-8"))
    entries = registry["entries"]
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for name in ("index.html", "app.js", "styles.css", "registry-data.js"):
        shutil.copy2(ROOT / "web" / name, out / name)
    urls = [f"{base}/"]
    for entry in entries:
        d = out / "trap" / entry["id"]
        d.mkdir(parents=True)
        (d / "index.html").write_text(trap_page(entry, base), encoding="utf-8")
        urls.append(f"{base}/trap/{entry['id']}/")
    (out / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{html.escape(u)}</loc></url>\n" for u in urls)
        + "</urlset>\n", encoding="utf-8")
    (out / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {base}/sitemap.xml\n",
                                    encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    return len(entries)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(ROOT / "_site"))
    ap.add_argument("--base-url", default=DEFAULT_BASE)
    args = ap.parse_args()
    n = build(Path(args.out), args.base_url.rstrip("/"))
    print(f"built {n} trap pages into {args.out}")


if __name__ == "__main__":
    main()
